#!/usr/bin/env node
/** Generate crawler-visible SEO/AEO metadata from scripts/seo-config.mjs. */
import fs from 'node:fs';
import path from 'node:path';
import {
  SITE, INDEXABLE_ROUTES, NON_INDEXABLE_ROUTES, COMPANY_ENTITIES, GROUP_MARKETS,
  GROUP_VERTICALS, PAGE_METADATA, SEARCH_INTENTS,
  SEARCH_ENGINE_VERIFICATION,
  ROUTE_LABELS, absoluteUrl, publishedLocalesFor, localePath,
} from './seo-config.mjs';

const root = path.resolve(import.meta.dirname, '..');
const htmlFiles = fs.readdirSync(root).filter((file) => file.endsWith('.html')).sort();
const indexable = new Set(INDEXABLE_ROUTES);
const nonIndexable = new Set(NON_INDEXABLE_ROUTES);

function decode(value) {
  return value.replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&apos;/g, "'");
}

function escapeHtmlText(value) {
  return value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function attribute(html, name) {
  const tag = html.match(new RegExp(`<meta\\b[^>]*\\bname=["']${name}["'][^>]*>`, 'i'))?.[0]
    || html.match(new RegExp(`<meta\\b[^>]*\\bproperty=["']${name}["'][^>]*>`, 'i'))?.[0];
  return tag?.match(/\bcontent=(["'])([\s\S]*?)\1/i)?.[2] || '';
}

function title(html, file) {
  return decode(PAGE_METADATA[file]?.title || html.match(/<title>([\s\S]*?)<\/title>/i)?.[1]?.replace(/\s+/g, ' ').trim() || SITE.name);
}

function description(html, file) {
  return decode(PAGE_METADATA[file]?.description || attribute(html, 'description') || `${SITE.name} — East and Central Africa.`);
}

function breadcrumb(file, pageTitle) {
  const items = [{ '@type': 'ListItem', position: 1, name: 'Home', item: absoluteUrl('index.html') }];
  const company = COMPANY_ENTITIES[file];
  if (company) {
    items.push({ '@type': 'ListItem', position: 2, name: 'Business Verticals', item: absoluteUrl('index.html') });
    items.push({ '@type': 'ListItem', position: 3, name: company.sector, item: absoluteUrl('index.html') });
    items.push({ '@type': 'ListItem', position: 4, name: company.name, item: absoluteUrl(file) });
  } else {
    items.push({ '@type': 'ListItem', position: 2, name: ROUTE_LABELS[file] || pageTitle, item: absoluteUrl(file) });
  }
  return { '@type': 'BreadcrumbList', '@id': `${absoluteUrl(file)}#breadcrumb`, itemListElement: items };
}

function areaServed(value) {
  if (!value) return undefined;
  return (Array.isArray(value) ? value : [value]).map((name) => ({ '@type': 'Place', name }));
}

function topicsFor(file) {
  const intent = SEARCH_INTENTS[file];
  return intent ? [intent.primary, ...(intent.secondary || [])] : undefined;
}

function schema(file, pageTitle, pageDescription) {
  if (!indexable.has(file)) return null;
  const url = absoluteUrl(file);
  const graph = [{
    '@type': 'WebPage', '@id': `${url}#webpage`, url, name: pageTitle,
    description: pageDescription, inLanguage: 'en',
    isPartOf: { '@id': SITE.websiteId }, about: { '@id': SITE.organizationId },
  }];
  if (file === 'index.html') {
    graph.push({
      '@type': 'Organization', '@id': SITE.organizationId, name: SITE.name,
      legalName: SITE.name, url: SITE.origin + '/', logo: SITE.origin + SITE.logo,
      description: pageDescription, foundingDate: '2006',
      address: { '@type': 'PostalAddress', streetAddress: 'Plot 49, Mikocheni Light Industrial', addressLocality: 'Dar es Salaam', addressCountry: 'TZ' },
      telephone: '+255 222 780 510', email: 'admin@lakeoilgroup.com',
      areaServed: areaServed(GROUP_MARKETS), knowsAbout: GROUP_VERTICALS,
      sameAs: ['https://youtube.com/@lakegroup6790?si=Qb1aF3ghYIRdCM8J', 'https://www.instagram.com/lakeenergiestanzania?igsi=cW5jZGVtbHU0eGFs'],
    });
    graph.push({
      '@type': 'WebSite', '@id': SITE.websiteId, url: SITE.origin + '/', name: SITE.name,
      inLanguage: 'en', publisher: { '@id': SITE.organizationId }, about: { '@id': SITE.organizationId },
    });
  }
  if (COMPANY_ENTITIES[file]) {
    const company = COMPANY_ENTITIES[file];
    graph.push({
      '@type': 'Organization', '@id': `${url}#organization`, name: company.name,
      url, description: pageDescription, parentOrganization: { '@id': SITE.organizationId },
      areaServed: areaServed(company.areaServed), knowsAbout: topicsFor(file),
    });
    graph[0].about = { '@id': `${url}#organization` };
    graph[0].mainEntity = { '@id': `${url}#organization` };
  }
  if (file === 'africa-network.html') graph[0].mentions = areaServed(GROUP_MARKETS);
  if (file !== 'index.html') graph.push(breadcrumb(file, pageTitle));
  return { '@context': 'https://schema.org', '@graph': graph };
}

function managedHead(file, pageTitle, pageDescription) {
  const url = absoluteUrl(file);
  const isIndexable = indexable.has(file);
  const lines = [
    '<!-- SEO:START (generated by scripts/build-seo-foundation.mjs) -->',
    `<meta name="description" content="${pageDescription.replace(/"/g, '&quot;')}">`,
    `<meta name="robots" content="${isIndexable ? 'index,follow,max-image-preview:large' : 'noindex,nofollow'}">`,
    `<link rel="canonical" href="${url}">`,
    `<meta property="og:title" content="${pageTitle.replace(/"/g, '&quot;')}">`,
    `<meta property="og:description" content="${pageDescription.replace(/"/g, '&quot;')}">`,
    `<meta property="og:image" content="${SITE.origin + SITE.socialImage}">`,
    `<meta property="og:image:width" content="1200">`,
    `<meta property="og:image:height" content="630">`,
    '<meta property="og:image:type" content="image/jpeg">',
    '<meta property="og:type" content="website">',
    `<meta property="og:url" content="${url}">`,
    `<meta property="og:site_name" content="${SITE.name}">`,
    `<meta property="og:locale" content="${SITE.locale}">`,
    '<meta name="twitter:card" content="summary_large_image">',
    `<meta name="twitter:title" content="${pageTitle.replace(/"/g, '&quot;')}">`,
    `<meta name="twitter:description" content="${pageDescription.replace(/"/g, '&quot;')}">`,
    `<meta name="twitter:image" content="${SITE.origin + SITE.socialImage}">`,
  ];
  if (SEARCH_ENGINE_VERIFICATION.google) lines.push(`<meta name="google-site-verification" content="${SEARCH_ENGINE_VERIFICATION.google.replace(/"/g, '&quot;')}">`);
  if (SEARCH_ENGINE_VERIFICATION.bing) lines.push(`<meta name="msvalidate.01" content="${SEARCH_ENGINE_VERIFICATION.bing.replace(/"/g, '&quot;')}">`);
  for (const locale of publishedLocalesFor(file)) {
    lines.push(`<link rel="alternate" hreflang="${locale}" href="${SITE.origin + localePath(file, locale)}">`);
  }
  if (publishedLocalesFor(file).length) lines.push(`<link rel="alternate" hreflang="x-default" href="${url}">`);
  const data = schema(file, pageTitle, pageDescription);
  if (data) lines.push(`<script type="application/ld+json">${JSON.stringify(data)}</script>`);
  lines.push('<!-- SEO:END -->');
  return lines.join('\n  ');
}

function replaceManagedHead(html, file) {
  const pageTitle = title(html, file);
  const pageDescription = description(html, file);
  html = html
    .replace(/\s*<!-- SEO:START \(generated by scripts\/build-seo-foundation\.mjs\) -->[\s\S]*?<!-- SEO:END -->/g, '')
    .replace(/\s*<meta\b[^>]*\b(?:name|property)=["'](?:description|robots|twitter:[^"']+|og:[^"']+)["'][^>]*>/gi, '')
    .replace(/\s*<link\b[^>]*\brel=["']canonical["'][^>]*>/gi, '')
    .replace(/\s*<link\b[^>]*\brel=["']alternate["'][^>]*\bhreflang=["'][^"']+["'][^>]*>/gi, '')
    .replace(/\s*<script\b[^>]*type=["']application\/ld\+json["'][^>]*>[\s\S]*?<\/script>/gi, '');
  html = html.replace(/<title>[\s\S]*?<\/title>/i, `<title>${escapeHtmlText(pageTitle)}</title>`);
  return html.replace(/<\/head>/i, `  ${managedHead(file, pageTitle, pageDescription)}\n</head>`);
}

const unknown = htmlFiles.filter((file) => !indexable.has(file) && !nonIndexable.has(file));
if (unknown.length) throw new Error(`Route classification missing: ${unknown.join(', ')}`);
let updated = 0;
for (const file of htmlFiles) {
  const full = path.join(root, file);
  const before = fs.readFileSync(full, 'utf8');
  const after = replaceManagedHead(before, file);
  if (after !== before) { fs.writeFileSync(full, after, 'utf8'); updated += 1; }
}
console.log(`SEO foundation generated for ${htmlFiles.length} routes; ${updated} files updated.`);
