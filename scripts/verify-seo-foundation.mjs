#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { INDEXABLE_ROUTES, NON_INDEXABLE_ROUTES, SITE } from './seo-config.mjs';

const root = path.resolve(import.meta.dirname, '..');
const errors = [];
const all = [...INDEXABLE_ROUTES, ...NON_INDEXABLE_ROUTES];
const titles = new Map();
const descriptions = new Map();
for (const file of all) {
  const html = fs.readFileSync(path.join(root, file), 'utf8');
  const indexable = INDEXABLE_ROUTES.includes(file);
  const url = `${SITE.origin}${file === 'index.html' ? '/' : `/${file}`}`;
  const required = [
    /<html[^>]+lang="en"/i, /<title>[\s\S]+?<\/title>/i,
    /<!-- SEO:START \(generated by scripts\/build-seo-foundation\.mjs\) -->/,
    new RegExp(`<link rel="canonical" href="${url.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}">`),
    new RegExp(`name="robots" content="${indexable ? 'index,follow,max-image-preview:large' : 'noindex,nofollow'}"`),
    /property="og:title"/, /property="og:description"/, /property="og:url"/,
    /name="twitter:card"/,
  ];
  if (indexable) required.push(/type="application\/ld\+json"/);
  required.forEach((check, i) => { if (!check.test(html)) errors.push(`${file}: missing SEO check ${i + 1}`); });
  if ((html.match(/rel="canonical"/g) || []).length !== 1) errors.push(`${file}: canonical is not unique`);
  if ((html.match(/name="description"/g) || []).length !== 1) errors.push(`${file}: description is not unique`);
  if ((html.match(/type="application\/ld\+json"/g) || []).length > 1) errors.push(`${file}: JSON-LD is duplicated`);
  if (/lakegroup\.vercel\.app/i.test(html)) errors.push(`${file}: contains a Vercel preview-domain URL`);
  const pageTitle = html.match(/<title>([\s\S]*?)<\/title>/i)?.[1]?.trim();
  const pageDescription = html.match(/<meta name="description" content="([\s\S]*?)">/i)?.[1]?.trim();
  if (indexable && (!pageTitle || !pageDescription)) errors.push(`${file}: title or description is empty`);
  if (indexable) {
    if (titles.has(pageTitle)) errors.push(`${file}: title duplicates ${titles.get(pageTitle)}`);
    else titles.set(pageTitle, file);
    if (descriptions.has(pageDescription)) errors.push(`${file}: description duplicates ${descriptions.get(pageDescription)}`);
    else descriptions.set(pageDescription, file);
  }
  const scripts = [...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)];
  scripts.forEach((match) => { try { JSON.parse(match[1]); } catch { errors.push(`${file}: malformed JSON-LD`); } });
}
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }
console.log(`SEO validation passed: ${INDEXABLE_ROUTES.length} indexable + ${NON_INDEXABLE_ROUTES.length} non-indexable routes.`);
